// Bakes Natural Earth 110m land polygons into a compact 1°×1° land bitmask.
// Output: src/data/landMask.ts (base64, ~11 KB) consumed by the interactive globe.
// Run: node scripts/bake-land-mask.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const __dir = dirname(fileURLToPath(import.meta.url));
const geo = JSON.parse(readFileSync(resolve(__dir, '_ne_110m_land.json'), 'utf8'));

const W = 360; // longitude cells (-180..180)
const H = 180; // latitude cells (90..-90, north-first)

// Precompute rings with bounding boxes: each Polygon = [outerRing, ...holes].
const polys = geo.features.map((f) => {
  const rings = f.geometry.coordinates.map((ring) => {
    let minX = Infinity, minY = Infinity, maxX = -Infinity, maxY = -Infinity;
    for (const [x, y] of ring) {
      if (x < minX) minX = x;
      if (x > maxX) maxX = x;
      if (y < minY) minY = y;
      if (y > maxY) maxY = y;
    }
    return { ring, minX, minY, maxX, maxY };
  });
  return rings;
});

function pointInRing(px, py, r) {
  if (px < r.minX || px > r.maxX || py < r.minY || py > r.maxY) return false;
  const pts = r.ring;
  let inside = false;
  for (let i = 0, j = pts.length - 1; i < pts.length; j = i++) {
    const xi = pts[i][0], yi = pts[i][1];
    const xj = pts[j][0], yj = pts[j][1];
    if ((yi > py) !== (yj > py)) {
      const xint = ((xj - xi) * (py - yi)) / (yj - yi) + xi;
      if (px < xint) inside = !inside;
    }
  }
  return inside;
}

function isLand(lng, lat) {
  for (const rings of polys) {
    const outer = rings[0];
    if (!pointInRing(lng, lat, outer)) continue;
    let inHole = false;
    for (let h = 1; h < rings.length; h++) {
      if (pointInRing(lng, lat, rings[h])) { inHole = true; break; }
    }
    if (!inHole) return true;
  }
  return false;
}

const totalBits = W * H;
const bytes = new Uint8Array(Math.ceil(totalBits / 8));
let land = 0;
for (let y = 0; y < H; y++) {
  const lat = 90 - y - 0.5; // sample cell centre
  for (let x = 0; x < W; x++) {
    const lng = -180 + x + 0.5;
    if (isLand(lng, lat)) {
      const bit = y * W + x;
      bytes[bit >> 3] |= 0x80 >> (bit & 7);
      land++;
    }
  }
}

const b64 = Buffer.from(bytes).toString('base64');
const out = `// AUTO-GENERATED by scripts/bake-land-mask.mjs — do not edit by hand.
// 1°×1° land bitmask from Natural Earth 110m land, row-major (north-first), MSB-first.
export const LAND_MASK = {
  width: ${W},
  height: ${H},
  /** base64 of a ${Math.ceil(totalBits / 8)}-byte packed bit grid; 1 = land. */
  bits: '${b64}',
} as const;
`;
writeFileSync(resolve(__dir, '..', 'src', 'data', 'landMask.ts'), out);
console.log(`baked ${land} land cells / ${totalBits} (${((land / totalBits) * 100).toFixed(1)}%) → src/data/landMask.ts (${b64.length} b64 chars)`);
