// Bakes Natural Earth 110m land into simplified world coastline rings for the globe backdrop.
// Output: src/data/worldLand.ts   Run: node scripts/bake-world-land.mjs  (needs scripts/_ne_110m_land.json)
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const __dir = dirname(fileURLToPath(import.meta.url));
const geo = JSON.parse(readFileSync(resolve(__dir, '_ne_110m_land.json'), 'utf8'));

function perp(p, a, b) {
  const dx = b[0] - a[0], dy = b[1] - a[1];
  const l2 = dx * dx + dy * dy;
  if (l2 === 0) return Math.hypot(p[0] - a[0], p[1] - a[1]);
  let t = ((p[0] - a[0]) * dx + (p[1] - a[1]) * dy) / l2;
  t = Math.max(0, Math.min(1, t));
  return Math.hypot(p[0] - (a[0] + t * dx), p[1] - (a[1] + t * dy));
}
function dp(pts, tol) {
  if (pts.length < 4) return pts;
  let max = 0, idx = 0;
  for (let i = 1; i < pts.length - 1; i++) {
    const d = perp(pts[i], pts[0], pts[pts.length - 1]);
    if (d > max) { max = d; idx = i; }
  }
  if (max > tol) return dp(pts.slice(0, idx + 1), tol).slice(0, -1).concat(dp(pts.slice(idx), tol));
  return [pts[0], pts[pts.length - 1]];
}
function area(r) {
  let a = 0;
  for (let i = 0, j = r.length - 1; i < r.length; j = i++) a += (r[j][0] + r[i][0]) * (r[j][1] - r[i][1]);
  return Math.abs(a / 2);
}

const q = (n) => Math.round(n * 100) / 100;
const AREA_MIN = 1.4; // drop tiny specks (deg²)
const TOL = 0.45;

const rings = [];
let kept = 0, dropped = 0;
for (const f of geo.features) {
  for (const ring of f.geometry.coordinates) {
    if (area(ring) < AREA_MIN) { dropped++; continue; }
    const s = dp(ring, TOL);
    if (s.length < 4) { dropped++; continue; }
    const flat = [];
    for (const [lng, lat] of s) flat.push(q(lng), q(lat));
    rings.push(flat);
    kept++;
  }
}

const total = rings.reduce((n, r) => n + r.length / 2, 0);
const body = rings.map((r) => `  [${r.join(',')}],`).join('\n');
const out = `// AUTO-GENERATED by scripts/bake-world-land.mjs — do not edit by hand.
// Simplified Natural Earth 110m world coastlines. Rings are flat [lng,lat,lng,lat,…] arrays.
export const WORLD_LAND: number[][] = [
${body}
];
`;
writeFileSync(resolve(__dir, '..', 'src', 'data', 'worldLand.ts'), out);
console.log(`world land: kept ${kept} rings (dropped ${dropped}), ${total} vertices → src/data/worldLand.ts (${(out.length / 1024).toFixed(1)} KB)`);
