// Bakes Natural Earth 50m admin-0 country borders for the ~52 WatchTower countries into a
// compact, simplified shape table for the interactive globe.
// Output: src/data/countryShapes.ts
// Run: node scripts/bake-country-shapes.mjs   (needs scripts/_ne50_countries.json)
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const __dir = dirname(fileURLToPath(import.meta.url));
const geo = JSON.parse(readFileSync(resolve(__dir, '_ne50_countries.json'), 'utf8'));

const NEED = [
  'AUS','AUT','BLR','BEL','BIH','BGR','CAN','HRV','CYP','CZE','DNK','EST','FIN','FRA','DEU',
  'GRC','HUN','ISL','IRL','ITA','LVA','LIE','LTU','LUX','MLT','MDA','MCO','MNE','NLD','NZL',
  'NOR','POL','PRT','ROU','RUS','SRB','ZAF','SVK','SVN','ESP','SWE','CHE','UKR','GBR','USA',
  'ALB','AND','ARM','AZE','GEO','MKD','SMR',
];

const byIso = {};
for (const f of geo.features) byIso[f.properties.ADM0_A3] = f;

// --- Douglas–Peucker (planar on lng/lat; fine at this scale).
function perpDist(p, a, b) {
  const dx = b[0] - a[0], dy = b[1] - a[1];
  const len2 = dx * dx + dy * dy;
  if (len2 === 0) return Math.hypot(p[0] - a[0], p[1] - a[1]);
  let t = ((p[0] - a[0]) * dx + (p[1] - a[1]) * dy) / len2;
  t = Math.max(0, Math.min(1, t));
  return Math.hypot(p[0] - (a[0] + t * dx), p[1] - (a[1] + t * dy));
}
function dp(points, tol) {
  if (points.length < 3) return points;
  let maxD = 0, idx = 0;
  for (let i = 1; i < points.length - 1; i++) {
    const d = perpDist(points[i], points[0], points[points.length - 1]);
    if (d > maxD) { maxD = d; idx = i; }
  }
  if (maxD > tol) {
    const left = dp(points.slice(0, idx + 1), tol);
    const right = dp(points.slice(idx), tol);
    return left.slice(0, -1).concat(right);
  }
  return [points[0], points[points.length - 1]];
}

function ringArea(ring) {
  let a = 0;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    a += (ring[j][0] + ring[i][0]) * (ring[j][1] - ring[i][1]);
  }
  return Math.abs(a / 2);
}
function centroid(ring) {
  let x = 0, y = 0, a = 0;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const cross = ring[j][0] * ring[i][1] - ring[i][0] * ring[j][1];
    x += (ring[j][0] + ring[i][0]) * cross;
    y += (ring[j][1] + ring[i][1]) * cross;
    a += cross;
  }
  if (a === 0) return ring[0];
  a *= 0.5;
  return [x / (6 * a), y / (6 * a)];
}

const q = (n) => Math.round(n * 100) / 100; // ~0.01° quantization

const shapes = {};
let totalOut = 0;
for (const iso of NEED) {
  const f = byIso[iso];
  const g = f.geometry;
  const polys = g.type === 'Polygon' ? [g.coordinates] : g.coordinates;

  // outer rings with area; keep the biggest, plus any island bigger than threshold.
  const outers = polys.map((p) => ({ ring: p[0], area: ringArea(p[0]) }));
  const maxArea = Math.max(...outers.map((o) => o.area));
  const areaThresh = Math.max(maxArea * 0.02, 0.03); // drop tiny far islands

  const kept = outers
    .filter((o) => o.area === maxArea || o.area >= areaThresh)
    .sort((a, b) => b.area - a.area);

  // adaptive tolerance: simplify until the country is under ~220 output vertices.
  // Fall back to the original ring when DP would collapse a tiny country (e.g. Monaco).
  const simplify = (ring, tol) => {
    const s = dp(ring, tol);
    return s.length >= 4 ? s : ring;
  };
  let tol = 0.05;
  let ringsOut;
  for (let iter = 0; iter < 8; iter++) {
    ringsOut = kept.map((o) => simplify(o.ring, tol));
    const v = ringsOut.reduce((s, r) => s + r.length, 0);
    if (v <= 220) break;
    tol *= 1.6;
  }

  const flat = ringsOut
    .filter((r) => r.length >= 4)
    .map((r) => {
      const out = [];
      for (const [lng, lat] of r) out.push(q(lng), q(lat));
      return out;
    });
  totalOut += flat.reduce((s, r) => s + r.length / 2, 0);
  const anchor = centroid(kept[0].ring);
  shapes[iso] = { a: [q(anchor[0]), q(anchor[1])], r: flat };
}

const body = Object.entries(shapes)
  .map(([iso, s]) => {
    const rings = s.r.map((r) => `[${r.join(',')}]`).join(',\n    ');
    return `  ${iso}: { a: [${s.a[0]}, ${s.a[1]}], r: [\n    ${rings},\n  ] },`;
  })
  .join('\n');

const out = `// AUTO-GENERATED by scripts/bake-country-shapes.mjs — do not edit by hand.
// Simplified Natural Earth 50m admin-0 borders for the WatchTower globe.
// Each entry: a = [lng, lat] label anchor, r = rings as flat [lng, lat, lng, lat, …] arrays.
export interface CountryShape {
  a: [number, number];
  r: number[][];
}

export const COUNTRY_SHAPES: Record<string, CountryShape> = {
${body}
};
`;
writeFileSync(resolve(__dir, '..', 'src', 'data', 'countryShapes.ts'), out);
console.log(`baked ${NEED.length} countries, ${totalOut} vertices → src/data/countryShapes.ts (${(out.length / 1024).toFixed(1)} KB)`);
